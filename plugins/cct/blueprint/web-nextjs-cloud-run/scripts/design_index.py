"""One line per design and decision, so an agent reads the index and opens only what it needs.

    python3 scripts/design_index.py write    # regenerate <designsDir>/INDEX.md
    python3 scripts/design_index.py check    # exit 1 when INDEX.md is stale

Written by `sdlc-run adopt` from the kit; edit the kit, not this copy. stdlib only.

Every `*.md` under sdlc.json `designsDir` (default `docs/designs`) is one line, read from its
frontmatter: `title`, `type`, `status`, `created`, `tags`, `superseded_by`. Missing fields fall
back to the filename (`<date>-<type>-<slug>.md`) and the first `# ` heading. `INDEX.md`,
`README.md` and files starting with `_` are skipped. A superseded or deprecated document is
listed last, with what replaced it, so nobody builds on it by accident.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

GONE = {"superseded", "deprecated", "withdrawn", "rejected"}
TYPE_ORDER = ("adr", "spec", "design", "rfc", "note")
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
NAME = re.compile(r"^(?P<date>\d{4}-\d{2}-\d{2})-(?:(?P<type>[a-z]+)-)?")


def frontmatter(text: str) -> dict[str, str | list[str]]:
    """The scalar and list keys of a YAML frontmatter block: `k: v`, `k: [a, b]`, a bracket
    list over several lines, and a `- a` list. Nothing else is needed for an index."""
    m = FRONTMATTER.match(text)
    out: dict[str, str | list[str]] = {}
    if not m:
        return out
    key = ""
    for line in m.group(1).splitlines():
        top = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        s = line.strip()
        if top:
            key = top.group(1)
            out[key] = top.group(2).strip()
        elif key and s.startswith("- "):
            prev = out[key]
            out[key] = (prev if isinstance(prev, list) else []) + [s[2:].strip()]
        elif key and isinstance(out[key], str):
            out[key] = f"{out[key]} {s}".strip()  # a bracket list or a folded value
    for k, v in out.items():
        if isinstance(v, str) and v.startswith("[") and v.endswith("]"):
            out[k] = [unquote(x) for x in v[1:-1].split(",") if x.strip()]
        elif isinstance(v, str):
            out[k] = unquote(v)
    return out


def unquote(v: str) -> str:
    v = v.strip()
    return v[1:-1] if len(v) > 1 and v[0] == v[-1] and v[0] in "'\"" else v


def as_list(value: str | list[str] | None) -> list[str]:
    if not value or value in ("null", "none", "[]"):
        return []
    return value if isinstance(value, list) else [value]


def entries(designs: Path) -> list[dict[str, object]]:
    rows = []
    for path in sorted(designs.rglob("*.md")):
        if path.name in ("INDEX.md", "README.md") or path.name.startswith("_"):
            continue
        text = path.read_text(encoding="utf-8")
        fm = frontmatter(text)
        name = NAME.match(path.stem)
        heading = re.search(r"^# (.+)$", text, re.MULTILINE)
        rows.append(
            {
                "path": path.relative_to(designs).as_posix(),
                "id": fm.get("id") or path.stem,
                "title": fm.get("title") or (heading.group(1).strip() if heading else path.stem),
                "type": str(fm.get("type") or (name and name.group("type")) or "design"),
                "status": str(fm.get("status") or "unknown"),
                "created": str(fm.get("created") or (name and name.group("date")) or ""),
                "tags": as_list(fm.get("tags")),
                "by": as_list(fm.get("superseded_by")),
            }
        )
    return rows


def render(designs: Path) -> str:
    rows = entries(designs)
    current = [r for r in rows if r["status"] not in GONE]
    gone = [r for r in rows if r["status"] in GONE]
    out = [
        "# Designs and decisions",
        "",
        "GENERATED by `python3 scripts/design_index.py write`; do not edit by hand.",
        "Read this first. Open only the files whose title or tags touch your change.",
        "One line: title · status · date · tags. Newest first within each type.",
    ]

    def line(r: dict[str, object]) -> str:
        tags = ", ".join(r["tags"])  # type: ignore[arg-type]
        tail = f" · {tags}" if tags else ""
        by = f" → replaced by {', '.join(r['by'])}" if r["by"] else ""  # type: ignore[arg-type]
        return f"- [{r['title']}]({r['path']}) · {r['status']} · {r['created']}{tail}{by}"

    def rank(t: str) -> tuple[int, str]:
        return (TYPE_ORDER.index(t) if t in TYPE_ORDER else len(TYPE_ORDER), t)

    def newest(group: list[dict[str, object]]) -> list[dict[str, object]]:
        return sorted(group, key=lambda r: (str(r["created"]), str(r["path"])), reverse=True)

    for t in sorted({str(r["type"]) for r in current}, key=rank):
        group = newest([r for r in current if r["type"] == t])
        out += ["", f"## {t} ({len(group)})", ""] + [line(r) for r in group]
    if gone:
        out += ["", f"## Replaced ({len(gone)}): do not build on these", ""]
        out += [line(r) for r in newest(gone)]
    return "\n".join(out) + "\n"


def designs_dir(root: Path) -> Path:
    cfg_path = root / "sdlc.json"
    cfg = json.loads(cfg_path.read_text(encoding="utf-8")) if cfg_path.exists() else {}
    return root / cfg.get("designsDir", "docs/designs")


def main(argv: list[str]) -> int:
    mode = argv[1] if len(argv) > 1 else ""
    if mode not in ("write", "check"):
        print(__doc__)
        return 2
    designs = designs_dir(Path.cwd())
    index = designs / "INDEX.md"
    want = render(designs) if designs.is_dir() else ""
    if mode == "write":
        if want:
            index.write_text(want, encoding="utf-8")
            print(f"wrote {index}")
        return 0
    have = index.read_text(encoding="utf-8") if index.exists() else ""
    if want and have != want:
        print(f"{index} is stale: run `python3 scripts/design_index.py write` and commit it")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
