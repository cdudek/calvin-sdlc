def _counting_repo(tmp_path: Path) -> tuple[Path, Path]:
    repo = _git_repo_with(tmp_path, verify_exit=0)
    count = tmp_path / "count"
    cfg = json.loads((repo / "sdlc.json").read_text())
    cfg["verify"] = f"sh -c 'echo ran >> {count}'"
    (repo / "sdlc.json").write_text(json.dumps(cfg))
    # A CI runner has no git identity; pass one, as _git_repo_with does.
    subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qam", "count"],
        cwd=repo,
        check=True,
        env=_clean_env(),
    )
    return repo, count


def test_verify_on_stop_skips_when_the_dirty_diff_is_unchanged(tmp_path: Path) -> None:
    repo, count = _counting_repo(tmp_path)
    env = {"CLAUDE_PROJECT_DIR": str(repo)}
    (repo / "x.py").write_text("x = 1\n")
    for _ in range(2):
        assert _run_hook("verify-on-stop.sh", {}, env=env).returncode == 0
    assert count.read_text().count("ran") == 1
    (repo / "x.py").write_text("x = 2\n")
    assert _run_hook("verify-on-stop.sh", {}, env=env).returncode == 0
    assert count.read_text().count("ran") == 2


def test_verify_on_stop_skips_inside_an_active_goal(tmp_path: Path) -> None:
    repo, count = _counting_repo(tmp_path)
    (repo / "x.py").write_text("x = 1\n")
    transcript = tmp_path / "t.jsonl"
    env = {"CLAUDE_PROJECT_DIR": str(repo)}
    for met, ran in ((False, 0), (True, 1)):
        entry = {"type": "attachment", "attachment": {"type": "goal_status", "met": met}}
        transcript.write_text(json.dumps(entry) + "\n")
        payload = {"transcript_path": str(transcript)}
        assert _run_hook("verify-on-stop.sh", payload, env=env).returncode == 0
        assert (count.read_text().count("ran") if count.exists() else 0) == ran


