# <created>-<KEY>-<slug>, and <created>-<slug> when the change has no Linear issue.
# Open and archived folders have the same shape: archiving moves the folder, it never renames it.
CHANGE_DIR = re.compile(
    r"^(?P<date>\d{4}-\d{2}-\d{2})-(?:(?P<key>[A-Z][A-Z0-9]+-\d+)-)?(?P<slug>[a-z0-9][a-z0-9-]*)$"
)
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)


def _dirs(parent: Path) -> list[Path]:
    return (
        sorted(p for p in parent.iterdir() if p.is_dir() and p.name != "archive")
        if parent.is_dir()
        else []
    )


def _archive_dirs(parent: Path, depth: int = 2) -> list[Path]:
    # The archive nests by <year>/<year-month>/ so it stays readable past a few hundred
    # changes, the way docs/designs/ already does. Both layouts are walked: a repo that has
    # not run `adopt` since the migration still has a flat archive, and its history is not
    # wrong, just older. A directory is a change when its NAME matches CHANGE_DIR; anything
    # else at these two levels is a year or a month bucket.
    if not parent.is_dir():
        return []
    out: list[Path] = []
    for p in parent.iterdir():
        if not p.is_dir():
            continue
        if CHANGE_DIR.match(p.name):
            out.append(p)
        elif depth > 0:
            out.extend(_archive_dirs(p, depth - 1))
    return sorted(out, key=lambda p: p.name)


def _changes() -> list[tuple[Path, bool]]:
    return [(p, False) for p in _dirs(CHANGES)] + [(p, True) for p in _archive_dirs(ARCHIVE)]


def _frontmatter(path: Path) -> dict[str, str]:
    match = FRONTMATTER.match(path.read_text(encoding="utf-8"))
    assert match, f"{path.relative_to(REPO_ROOT)} has no YAML frontmatter"
    pairs = (line.split(":", 1) for line in match.group(1).splitlines() if ":" in line)
    return {k.strip(): v.strip() for k, v in pairs}


def _section(text: str, heading: str) -> str:
    if f"## {heading}" not in text:
        return ""
    body = text.split(f"## {heading}", 1)[1]
    return re.split(r"^## ", body, flags=re.MULTILINE)[0]


def _markdown_targets(text: str) -> list[str]:
    return [
        target.strip("<>")
        for target in re.findall(r"!?\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)", text)
    ]


def _resource_cells(intent: str) -> list[str]:
    rows = [
        [cell.strip() for cell in line.strip().strip("|").split("|")]
        for line in _section(intent, "Asks").splitlines()
        if line.strip().startswith("|")
    ]
    header = next((row for row in rows if row and row[0] == "#"), [])
    assert "Resources" in header, "intent.md ## Asks table is missing Resources"
    index = header.index("Resources")
    return [
        row[index] for row in rows if row and re.fullmatch(r"A\d+", row[0]) and len(row) > index
    ]


def _assert_repo_relative_target(repo: Path, markdown_file: Path, target: str) -> None:
    target = target.strip().strip("'\"")
    if not target or target.startswith("#"):
        return
    # A web link is reachable by every reader; a path on one machine is not.
    if re.match(r"^(https?|mailto):", target, re.I):
        return
    assert not (
        target.startswith("/")
        or target.startswith("~/")
        or re.match(r"^[A-Za-z][A-Za-z0-9+.-]*:", target)
    ), f"{markdown_file.relative_to(repo)} links outside the repo: {target}"
    path = target.split("#", 1)[0]
    if not path:
        return
    candidates = [(markdown_file.parent / path).resolve(), (repo / path).resolve()]
    for candidate in candidates:
        try:
            candidate.relative_to(repo.resolve())
        except ValueError:
            continue
        if candidate.exists():
            return
    raise AssertionError(f"{markdown_file.relative_to(repo)} links to missing resource: {target}")


def _assert_change_resources_stay_in_repo(repo: Path, change: Path) -> None:
    for markdown_file in change.rglob("*.md"):
        text = markdown_file.read_text(encoding="utf-8")
        for target in _markdown_targets(text):
            _assert_repo_relative_target(repo, markdown_file, target)
    intent = change / "intent.md"
    if not intent.exists():
        return
    for cell in _resource_cells(intent.read_text(encoding="utf-8")):
        if cell.strip().lower() in {"", "none"}:
            continue
        targets = _markdown_targets(cell) or re.split(r"\s*(?:,|<br\s*/?>)\s*", cell)
        for target in [t for t in targets if t and t.lower() != "none"]:
            _assert_repo_relative_target(repo, intent, target)


def _parts(change: Path) -> dict[str, str]:
    m = CHANGE_DIR.match(change.name)
    assert m, f"{change.name}: wrong shape"
    return {k: v or "" for k, v in m.groupdict().items()}


