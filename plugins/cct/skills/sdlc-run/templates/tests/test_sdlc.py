def _goal_handover(plan: str) -> str:
    """The `/goal` step 6 hands over, pulled out of an approved plan.

    A section rather than a chat message because a handover that lives in one message
    is one that gets skipped with nothing downstream able to tell — folder, PR and every
    other assertion here look complete without it. `none - <why>` counts: a change whose
    deliverable IS the diff never had a build to hand over, and saying so is a decision
    while a blank section is a skip.
    """
    body = plan.split("## Goal handover")[1] if "## Goal handover" in plan else ""
    body = re.split(r"^## ", body, flags=re.MULTILINE)[0]
    kept = [
        line
        for line in body.splitlines()
        if not line.lstrip().startswith("<") and not line.lstrip().startswith("```")
    ]
    return "\n".join(kept).strip()


@pytest.mark.parametrize(
    ("change", "archived"), _changes(), ids=lambda x: x.name if isinstance(x, Path) else ""
)
def test_an_approved_plan_hands_its_goal_over(change: Path, archived: bool) -> None:
    # ARCHIVED CHANGES ARE EXEMPT, and that is why this is its own test rather than an
    # entry in PLAN_SECTIONS. An archived folder is an immutable record - "moved
    # verbatim, never renamed" - so a new required section applied to history fails
    # every change ever shipped. It did: 61 tests across omr-leadhub's archive, the
    # first time this ran. The rule is for work going forward; history is evidence.
    if archived:
        return
    plan_path = change / "plan.md"
    # And only once the gate has approved it. A draft has nothing to hand over yet,
    # and failing one would make the gate impossible to reach.
    if _frontmatter(plan_path).get("status") != "approved":
        return
    assert _goal_handover(plan_path.read_text(encoding="utf-8")) != "", (
        f"{change.name}: ## Goal handover is missing or empty. Put the /goal from step 6 there, "
        f'or "none - <why>".'
    )


@pytest.mark.parametrize(
    ("change", "archived"), _changes(), ids=lambda x: x.name if isinstance(x, Path) else ""
)
def test_plan_stands_on_approved_facts_and_intent_is_recorded(change: Path, archived: bool) -> None:
    # The backstop for chain-gate.sh. The hook refuses these writes while they can still be
    # fixed; this catches a folder that reached the repo without the hook - CI, another
    # machine, a repo adopted mid-change. Archived folders are exempt for the same reason
    # the handover rule exempts them: history is evidence, not a target.
    if archived:
        return
    # And only once the plan is approved, exactly like the handover rule above. A draft
    # plan beside draft facts is the legitimate in-flight state - facts are reviewed, then
    # the plan is written against them - and failing it would make the chain unreachable.
    # adopt's own seeded first change is the proof: it ships both files as drafts.
    if _frontmatter(change / "plan.md").get("status") != "approved":
        return
    assert _frontmatter(change / "facts.md").get("status") == "approved", (
        f"{change.name}: plan.md exists but facts.md is not approved. "
        f"Facts are reviewed before a plan is written against them."
    )
    decisions = change / "decisions.json"
    recorded = (change / "intent.md").exists() or (
        decisions.exists()
        and str(json.loads(decisions.read_text(encoding="utf-8")).get("intent", "")).startswith(
            "skip"
        )
    )
    assert recorded, (
        f"{change.name}: no intent.md and no recorded skip. Write the intent, or record why it "
        f"was skipped in decisions.json - a silent skip and a forgotten one look identical."
    )


@pytest.mark.parametrize(
    ("change", "archived"), _changes(), ids=lambda x: x.name if isinstance(x, Path) else ""
)
def test_v3_approved_plan_has_spec_guardrails(change: Path, archived: bool) -> None:
    if archived or not (change / "decisions.json").exists():
        return
    decisions = json.loads((change / "decisions.json").read_text(encoding="utf-8"))
    if "size" not in decisions:
        return
    if _frontmatter(change / "plan.md").get("status") != "approved":
        return
    assert decisions.get("size") in V3_SIZES, f"{change.name}: size"
    assert decisions.get("kind") in V3_KINDS, f"{change.name}: kind"
    skips = decisions.get("skips", {})
    files = {
        "brief": change / "spec" / "brief.md",
        "ia": change / "spec" / "ia.md",
        "interaction": change / "spec" / "interaction.md",
        "screens": change / "spec" / "screens.md",
        "prototype": change / "spec" / "prototype" / "index.md",
        "conformance": change / "spec" / "conformance.md",
        "validation": change / "spec" / "validation.md",
    }
    for activity in V3_ACTIVITIES:
        skipped = str(skips.get(activity, "")).startswith("skip")
        assert skipped or files[activity].exists(), f"{change.name}: {activity}"
    if not str(skips.get("validation", "")).startswith("skip"):
        fm = _frontmatter(change / "spec" / "validation.md")
        assert fm.get("verdict") == "ready" and fm.get("status") == "approved"
    _assert_change_resources_stay_in_repo(REPO_ROOT, change)
    # A recorded intent skip means there is no intent.md to read, and the check above has
    # already accepted that. Reading it regardless raised a bare FileNotFoundError — not an
    # assertion message, just a traceback naming a file the chain said need not exist
    # (omr-leadhub, two changes, 2026-10-17). Guard it the way `validation` is guarded.
    # Everything after this block still runs: a skipped intent says nothing about whether a
    # bug locked its test.
    if (change / "intent.md").exists():
        intent = (change / "intent.md").read_text(encoding="utf-8")
        asks = sorted(set(re.findall(r"\|\s*(A\d+)\s*\|", _section(intent, "Asks"))))
        assert asks, f"{change.name}: ## Asks has no A<n>"
        facts = (change / "facts.md").read_text(encoding="utf-8")
        missing = [a for a in asks if not re.search(rf"\b{a}\b", facts)]
        assert not missing, f"{change.name}: asks missing from facts.md: {missing}"
    if decisions.get("kind") == "bug":
        assert decisions.get("testLocked") is True, f"{change.name}: bug must lock the failing test"


