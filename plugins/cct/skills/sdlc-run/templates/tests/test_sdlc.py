# One unformatted line per language the test knows. The matching file comes from this repo's
# own `lintOnEdit` globs, so a repo that formats only TypeScript is tested on TypeScript.
UGLY = {
    "py": "x = [1,2,3 ]\n",
    "ts": "const x = [1,2,3 ]\n",
    "tsx": "const x = [1,2,3 ]\n",
    "js": "const x = [1,2,3 ]\n",
    "mjs": "const x = [1,2,3 ]\n",
}
LINT_GLOBS = [g for key in CFG.get("lintOnEdit", {}) for g in key.split()]
LINT_EXT = next(
    (m.group(1) for g in LINT_GLOBS if (m := re.fullmatch(r"\*\.(\w+)", g)) and m.group(1) in UGLY),
    None,
)


def test_lint_on_edit_formats_the_matching_file_and_only_that(tmp_path: Path) -> None:
    if not LINT_GLOBS:
        pytest.skip("sdlc.json lintOnEdit is empty")
    if not LINT_EXT:
        pytest.skip(f"no known unformatted sample for any lintOnEdit glob ({' '.join(LINT_GLOBS)})")
    ugly = UGLY[LINT_EXT]
    matching = tmp_path / f"ugly.{LINT_EXT}"
    matching.write_text(ugly, encoding="utf-8")
    other = tmp_path / "notes.txt"
    other.write_text(ugly, encoding="utf-8")
    assert (
        _run_hook("lint-on-edit.sh", {"tool_input": {"file_path": str(matching)}}).returncode == 0
    )
    assert _run_hook("lint-on-edit.sh", {"tool_input": {"file_path": str(other)}}).returncode == 0
    assert matching.read_text(encoding="utf-8") != ugly
    assert other.read_text(encoding="utf-8") == ugly


