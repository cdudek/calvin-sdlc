def _git_repo_with(tmp_path: Path, verify_exit: int) -> Path:
    repo = tmp_path / "repo"
    repo.mkdir()
    env = _clean_env()
    subprocess.run(["git", "init", "-q"], cwd=repo, check=True, env=env)
    (repo / "sdlc.json").write_text(
        json.dumps(
            {"verify": f"sh -c 'echo verify-ran; exit {verify_exit}'", "verifyDirty": ["*.py"]}
        )
    )
    subprocess.run(["git", "add", "."], cwd=repo, check=True, env=env)
    subprocess.run(
        ["git", "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-qm", "init"],
        cwd=repo,
        check=True,
        env=env,
    )
    return repo


def _chain_repo(
    tmp_path: Path,
    decisions: dict,
    *,
    asks: bool = True,
    resource_target: str = "asks/2026-10-06/session.md",
    design_done: bool = False,
    validation: str = "",
    facts_status: str = "approved",
    plan: bool = True,
) -> tuple[Path, str]:
    repo = tmp_path / f"chain-{len(list(tmp_path.iterdir()))}"
    repo.mkdir()
    env = _clean_env()
    subprocess.run(["git", "init", "-q", "-b", "feature/v3-change"], cwd=repo, check=True, env=env)
    (repo / "sdlc.json").write_text(
        json.dumps(
            {
                "changesDir": "changes",
                "docs": "docs/sdlc.md",
                "verify": "true",
                "verifyDirty": ["*.ts"],
                "prototypeDirs": ["proto"],
                "testGlobs": ["**/*.test.ts", "tests/**"],
            }
        )
    )
    change = "2026-10-06-v3-change"
    d = repo / "changes" / change
    (d / "spec").mkdir(parents=True)
    (d / "decisions.json").write_text(json.dumps(decisions))
    if (
        asks
        and resource_target
        and not (
            resource_target.startswith("/")
            or resource_target.startswith("~/")
            or resource_target.startswith("file://")
            or re.match(r"^[A-Za-z][A-Za-z0-9+.-]*:", resource_target)
        )
    ):
        resource = d / resource_target
        resource.parent.mkdir(parents=True, exist_ok=True)
        resource.write_text("owner feedback\n", encoding="utf-8")
    asks_body = (
        "## Asks\n\n| # | Date | Source | Words | Screen | Resources |\n"
        "|---|---|---|---|---|---|\n"
        f'| A1 | 2026-10-06 | owner, chat | "do it" | Screen | [session]({resource_target}) |\n'
        if asks
        else "## Asks\n\nnone\n"
    )
    (d / "intent.md").write_text(f"---\ntype: intent\n---\n\n# Intent\n\n{asks_body}")
    if design_done:
        for name in ("brief", "ia", "interaction", "screens", "conformance"):
            (d / "spec" / f"{name}.md").write_text(f"# {name}\n")
        (d / "spec" / "prototype").mkdir()
        (d / "spec" / "prototype" / "index.md").write_text("# prototype\n")
    if validation:
        (d / "spec" / "validation.md").write_text(validation)
    (d / "facts.md").write_text(
        f"---\ntype: facts\nstatus: {facts_status}\n---\n\n"
        "# Facts\n\n- [ ] **F1** (A1) When x, the system shall y.\n"
    )
    if plan:
        (d / "plan.md").write_text(
            "---\ntype: plan\nstatus: approved\n---\n\n# Plan\n\n## Goal handover\n\n/goal x\n"
        )
    return repo, change


