# Pairs, not a dict keyed by event: PreToolUse carries two hooks - gate-bash.sh for what
# sdlc.json blocks, chain-gate.sh for the chain's own gates - and a dict kept only one.
EXPECTED_HOOKS = [
    ("SessionStart", "session-check.sh"),
    ("PermissionRequest", "plan-gate.sh"),
    ("PreToolUse", "gate-bash.sh"),
    ("PreToolUse", "pr-gate.sh"),
    ("PreToolUse", "chain-gate.sh"),
    ("PostToolUse", "lint-on-edit.sh"),
    ("Stop", "verify-on-stop.sh"),
]
EXPECTED_DENY = {"Read(.env*)", "Read(**/secrets/**)", "Read(**/.secrets/**)"}


def test_settings_json_registers_every_hook_and_deny_rule() -> None:
    settings = json.loads(SETTINGS.read_text(encoding="utf-8"))
    assert EXPECTED_DENY <= set(settings["permissions"]["deny"])
    for event, script in EXPECTED_HOOKS:
        commands = [h["command"] for group in settings["hooks"][event] for h in group["hooks"]]
        assert any(script in c for c in commands), f"{event} does not run {script}"
        assert (HOOKS / script).is_file(), f"{script} missing"
        assert os.access(HOOKS / script, os.X_OK), f"{script} is not executable"


def test_hook_files_are_tracked_despite_the_global_gitignore() -> None:
    tracked = subprocess.run(
        ["git", "ls-files", ".claude/settings.json", ".claude/hooks", "sdlc.json"],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
        check=True,
    ).stdout.split()
    expected = {".claude/settings.json", "sdlc.json", ".claude/hooks/sdlc-config.sh"} | {
        f".claude/hooks/{s}" for _, s in EXPECTED_HOOKS
    }
    assert expected <= set(tracked), f"not tracked by git: {sorted(expected - set(tracked))}"


def _clean_env() -> dict[str, str]:
    return {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}


def _run_hook(
    script: str, payload: dict, env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [str(HOOKS / script)],
        input=json.dumps(payload),
        capture_output=True,
        text=True,
        env={**_clean_env(), "CLAUDE_PROJECT_DIR": str(REPO_ROOT), **(env or {})},
        timeout=120,
    )


